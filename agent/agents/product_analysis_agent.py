            "  - Search '«COMP» location accessibility parking' → assess convenience",
            "  - Search '«COMP» online presence website' → check digital presence",
            "",
            "COMPREHENSIVE OUTPUT FORMAT:",
            "",
            "### [Competitor Name]",
            "**Business Type:** {domain} | **Founded:** [Year if available] | **Size:** [Size metric relevant to business type]",
            "**Rating:** X.X/5 ([N] reviews) | **Price Level:** [€/€€/€€€ or equivalent]",
            "",
            "**📍 Location & Operations:**",
            "- **Address:** [Verified full address]",
            "- **Hours:** [Detailed daily/weekly schedule]",  
            "- **Capacity:** [Capacity metric relevant to business type]",
            "- **Parking:** [Available/paid/street]",
            "- **Accessibility:** [Wheelchair access, public transport]",
            "",
            "**📦 Products & Services (VERIFIED):**",
            "- **Main Categories:** [List of product/service categories relevant to {domain}]",
            "- **Key Offerings:** [Specific products/services with prices]",
            "- **Price Range:** [Price range for main offerings]",
            "- **Specialties:** [Specializations or unique offerings]",
            "- **Inventory/Service Scope:** [What's available or offered]",
