            "- DO NOT repeat company name excessively in the same paragraph",
            "- Keep analysis concise and non-redundant",
            "- Use bullet points and tables instead of repetitive text",
            "",
            "COMPLETION RULES:",
            "- ALWAYS complete every competitor section started",
            "- DO NOT leave sections unfinished or incomplete",
            "- Ensure proper table formatting with all columns filled",
