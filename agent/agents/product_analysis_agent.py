            COMPLETION_RULE_INSTRUCTION,
            "",
            DOMAIN_ADAPTATION_INSTRUCTION,
            "",
            "Perform comprehensive analysis of offerings for each competitor in {domain} in {location}. Adapt your analysis to the specific business type ({domain}).",
            "",
            "IMPORTANT - YOU MUST PRODUCE OUTPUT:",
            "- After searching, you MUST write analysis content for each competitor",
            "- Do NOT just do searches and stop - you must synthesize and write the analysis",
            "- Start your response with ### headers for each business",
            "- If you find no data, write 'No data available' but continue to the next competitor",
            "- Output at least 500 words of analysis content - do not be overly brief",
            "",
            COMPETITOR_ANALYSIS_INSTRUCTION,
            "In example search strings below, «COMP» means substitute that competitor's exact business name.",
            "",
            "SEARCH STRATEGY - FOLLOW THIS EXACT PROCESS:",
            "1. First search: '[Competitor Name] {location} official website'",
            "2. Second search: '[Competitor Name] menu offerings {location}'",
            "3. Third search: '[Competitor Name] reviews what they are known for {location}'",
            "4. If still no data, search '[Competitor Name] {domain} {location}'",
            "",
            "UNIVERSAL SEARCH PROCESS:",
            "  Step 1: Search '«COMP» {domain} {location}' → Find business information",
            "  Step 2: Search '«COMP» offerings services products {location}' → Find what they sell/provide",
            "  Step 3: Search '«COMP» website {location}' → Visit official site",
            "  Step 4: Search '«COMP» reviews {location}' → Check real customer feedback",
            "  Step 5: Search '«COMP» prices {location}' → Get real pricing",
            "",
            "DATA VERIFICATION RULES:",
            "- Verify all data points through actual web searches",
            "- Cross-check information from multiple sources before including",
            "- If information cannot be found, state 'Data not available' rather than guessing",
            "- Never assume features without verification",
            "- **Accessibility Verification:** NEVER assume wheelchair access, parking availability, or other accessibility features without explicit verification from official sources (website, Google Business Profile, or direct contact). Mark unverified accessibility as 'Needs confirmation' or 'Not verified'.",
            "- **Facility Claims:** Only include facility claims (parking, capacity, hours, amenities) if verified from official sources. If uncertain, mark as 'Needs verification'.",
            "- Cross-check data from multiple sources",
            "- Adapt output format based on business type (retail, service, food, etc.)",
            "",
            "FOR ALL BUSINESS TYPES:",
